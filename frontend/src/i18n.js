const FALLBACK_LANGUAGE = 'en'

const getFromDictionary = (language, key) =>
  key.split('.').reduce((value, segment) => value?.[segment], translations[language])

export const createTranslator = (language) => {
  return (key) => {
    const value = getFromDictionary(language, key)
    if (typeof value === 'string') {
      return value
    }

    const fallbackValue = getFromDictionary(FALLBACK_LANGUAGE, key)
    return typeof fallbackValue === 'string' ? fallbackValue : key
  }
}
